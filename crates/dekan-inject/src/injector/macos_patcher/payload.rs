fn validate_prefix(prefix: &str) -> Result<&[u8], String> {
    let bytes = prefix.as_bytes();
    if bytes.is_empty() || bytes.len() >= MAX_PREFIX_BYTES {
        return Err(format!(
            "overlay prefix length {} is outside 1..{MAX_PREFIX_BYTES}",
            bytes.len()
        ));
    }
    if bytes.contains(&0) {
        return Err("overlay prefix contains NUL byte".into());
    }
    Ok(bytes)
}

pub fn build_payload_x86_64(fopen_orig_addr: u64, prefix: &str) -> Result<Vec<u8>, String> {
    let prefix_bytes = validate_prefix(prefix)?;
    let mut out = Vec::with_capacity(SHELLCODE_X86_64.len() + 8 + 256);
    out.extend_from_slice(SHELLCODE_X86_64);
    out.extend_from_slice(&fopen_orig_addr.to_le_bytes());
    let mut prefix_buf = [0u8; 256];
    prefix_buf[..prefix_bytes.len()].copy_from_slice(prefix_bytes);
    out.extend_from_slice(&prefix_buf);
    Ok(out)
}

