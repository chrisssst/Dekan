pub fn encode_x86_64_stub_jmp(stub_addr: u64, target_addr: u64) -> Result<[u8; 6], String> {
    let rel = (target_addr as i64) - (stub_addr.wrapping_add(5) as i64);
    let rel32 = i32::try_from(rel)
        .map_err(|_| format!("x86_64 jump displacement out of i32 range: {rel}"))?;
    let bytes = rel32.to_le_bytes();
    Ok([0xE9, bytes[0], bytes[1], bytes[2], bytes[3], 0x90])
}

pub fn encode_arm64_stub_jmp(stub_addr: u64, target_addr: u64) -> Result<[u8; 12], String> {
    let page_diff = ((target_addr & !0xFFF) as i64) - ((stub_addr & !0xFFF) as i64);
    let imm21 = page_diff >> 12;
    if !(-1_048_576..=1_048_575).contains(&imm21) {
        return Err(format!("arm64 ADRP page offset out of range: {imm21}"));
    }
    let immlo = ((imm21 as u32) & 0x3) << 29;
    let immhi = (((imm21 as u32) >> 2) & 0x7FFFF) << 5;
    let adrp = 0x9000_0010u32 | immlo | immhi;

    let page_off = (target_addr & 0xFFF) as u32;
    let add = 0x9100_0210u32 | (page_off << 10);
    let br = 0xD61F_0200u32;

    let mut out = [0u8; 12];
    out[0..4].copy_from_slice(&adrp.to_le_bytes());
    out[4..8].copy_from_slice(&add.to_le_bytes());
    out[8..12].copy_from_slice(&br.to_le_bytes());
    Ok(out)
}
